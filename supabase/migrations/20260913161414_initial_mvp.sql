-- Recherche littérale, paginée : aucun regex issu d'une saisie utilisateur.
create function public.rechercher_catalogue(terme text default '', page_num integer default 0)
returns table(id bigint, ref_fabricant text, nom text, marque text, image_url text, offres jsonb)
language sql stable security invoker set search_path = '' as $$
 select p.id, p.ref_fabricant, p.nom, p.marque, p.image_url,
 coalesce((select jsonb_agg(jsonb_build_object(
   'id',pf.id,'fournisseur',f.nom,'prix',pf.prix,'nature_prix',pf.nature_prix,
   'conditionnement',pf.conditionnement,'date_verification',pf.date_verification,
   'url_produit',pf.url_produit) order by f.nom)
   from public.produits_fournisseurs pf join public.fournisseurs f on f.id=pf.fournisseur_id
   where pf.produit_id=p.id), '[]'::jsonb)
 from public.produits p
 where position(lower(left(coalesce(terme,''),100)) in lower(p.nom || ' ' || p.ref_fabricant || ' ' || p.marque)) > 0
 order by p.nom,p.id limit 24 offset (greatest(0,least(coalesce(page_num,0),100000)) * 24);
$$;
revoke all on function public.rechercher_catalogue(text,integer) from public;
grant execute on function public.rechercher_catalogue(text,integer) to anon, authenticated;

-- Ajout atomique, exécuté avec les droits et les règles RLS de l'appelant.
create function public.ajouter_au_panier(offre_id bigint, qte integer default 1)
returns bigint language plpgsql security invoker set search_path = '' as $$
declare owner_id uuid := auth.uid(); cart_id bigint; item_id bigint;
begin
 if owner_id is null then raise exception 'Connexion requise' using errcode='42501'; end if;
 if qte is null or qte < 1 or qte > 9999 then raise exception 'Quantité invalide' using errcode='22023'; end if;
 if not exists(select 1 from public.produits_fournisseurs pf where pf.id=offre_id) then
  raise exception 'Offre indisponible' using errcode='22023';
 end if;
 insert into public.paniers(client_id) values(owner_id) on conflict(client_id) do nothing;
 select p.id into cart_id from public.paniers p where p.client_id=owner_id;
 insert into public.articles_panier(panier_id,offre_id,quantite) values(cart_id,offre_id,qte)
 on conflict on constraint articles_panier_panier_id_offre_id_key do update
 set quantite=public.articles_panier.quantite + excluded.quantite
 returning id into item_id;
 return item_id;
end; $$;
revoke all on function public.ajouter_au_panier(bigint,integer) from public;
grant execute on function public.ajouter_au_panier(bigint,integer) to authenticated;
commit;
