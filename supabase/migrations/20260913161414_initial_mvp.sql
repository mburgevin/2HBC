begin;
create table public.segments_clients (
  id bigint generated by default as identity primary key,
  nom text not null unique, description text
);
create table public.clients (
  id uuid primary key references auth.users(id) on delete cascade,
  nom_complet text not null default '' check (length(nom_complet) <= 120),
  telephone text, adresse text,
  segment_id bigint references public.segments_clients(id),
  date_creation timestamptz not null default now()
);
create table public.categories (
  id bigint generated by default as identity primary key,
  nom text not null, parent_id bigint references public.categories(id),
  check (parent_id is distinct from id)
);
create table public.fournisseurs (
  id bigint generated by default as identity primary key,
  nom text not null unique, site_web text check (site_web is null or site_web ~ '^https://')
);
create table public.produits (
  id bigint generated by default as identity primary key,
  ref_fabricant text not null check (length(ref_fabricant) between 1 and 100),
  code_ean text check (code_ean is null or code_ean ~ '^[0-9]{8,14}$'),
  nom text not null, marque text not null default '',
  categorie_id bigint references public.categories(id),
  description text, specificite text, emballage_condition text,
  image_url text check (image_url is null or image_url ~ '^https://'),
  pdf_url text check (pdf_url is null or pdf_url ~ '^https://'),
  date_creation timestamptz not null default now(),
  unique (marque, ref_fabricant)
);
create table public.produits_fournisseurs (
  id bigint generated by default as identity primary key,
  produit_id bigint not null references public.produits(id) on delete restrict,
  fournisseur_id bigint not null references public.fournisseurs(id) on delete restrict,
  ref_fournisseur text,
  prix numeric(12,2) check (prix >= 0),
  devise text not null default 'EUR' check (devise = 'EUR'),
  nature_prix text not null default 'demonstration' check (nature_prix in ('demonstration','public','negocie')),
  conditionnement text,
  url_produit text check (url_produit is null or url_produit ~ '^https://'),
  date_verification timestamptz,
  date_creation timestamptz not null default now(),
  unique(produit_id, fournisseur_id)
);
create table public.paniers (
  id bigint generated by default as identity primary key,
  client_id uuid not null unique references public.clients(id) on delete cascade,
  date_creation timestamptz not null default now()
);
create table public.articles_panier (
  id bigint generated by default as identity primary key,
  panier_id bigint not null references public.paniers(id) on delete cascade,
  offre_id bigint not null references public.produits_fournisseurs(id) on delete restrict,
  quantite integer not null default 1 check (quantite between 1 and 9999),
  unique(panier_id, offre_id)
);
create table public.besoins_clients (
  id bigint generated by default as identity primary key,
  client_id uuid not null references public.clients(id) on delete cascade,
  categorie_id bigint references public.categories(id),
  marque text, produit text not null,
  quantite_annuelle integer check (quantite_annuelle >= 0),
  unite text, budget_estime numeric(12,2) check (budget_estime >= 0),
  date_saisie timestamptz not null default now()
);
create index on public.clients(segment_id);
create index on public.categories(parent_id);
create index on public.produits(categorie_id);
create index on public.produits(nom,id);
create index on public.produits_fournisseurs(fournisseur_id);
create index on public.articles_panier(offre_id);
create index on public.besoins_clients(client_id);
create index on public.besoins_clients(categorie_id);

